// Release signing is optional: the project builds without a keystore, and picks one up
// when keystore.properties exists. That file and the keystore itself are gitignored —
// losing the key forces an uninstall/reinstall, which destroys the app's data.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use(::load)
}

android {
    namespace = "com.edi.hub"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.edi.hub"
        minSdk = 30
        targetSdk = 36
        versionCode = 1
        versionName = "0.1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

        // Open Food Facts requires a descriptive User-Agent with a contact.
        // Value comes from gradle.properties so no personal address is committed.
        buildConfigField(
            "String",
            "OFF_CONTACT",
            "\"${project.findProperty("hub.contact") ?: "https://github.com/edi/hub"}\"",
        )
    }

    signingConfigs {
        if (keystoreProperties.isNotEmpty()) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            signingConfig = signingConfigs.findByName("release")
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    kotlin {
        jvmToolchain(21)
    }
}

